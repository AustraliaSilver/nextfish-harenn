#!/usr/bin/env python3
"""
GitHub Worker End-of-Shift Uploader:
  1. Gộp các file raw JSONL/JSON của worker thành 1 file .jsonl và đẩy lên HF Bucket (australia1/myrandombucket).
  2. Biên dịch & chạy C++ fast_pack để nén ngay file .jsonl đó sang .npz (HalfKPv3).
  3. Đẩy shard .npz + metadata .meta.json lên HF Dataset (australia1/harenn-hkv3-npz) để job cuối ca gom đăng lên Kaggle.
"""

import argparse
import glob
import json
import os
import shutil
import subprocess
import sys
import time
import zipfile
from datetime import datetime, timezone
from pathlib import Path

os.environ.setdefault("HF_XET_HIGH_PERFORMANCE", "1")


def compile_fast_pack(repo_dir: Path, bin_path: Path) -> Path:
    if bin_path.exists():
        return bin_path
    cpp_path = repo_dir / "fast_pack.cpp"
    if not cpp_path.exists():
        raise FileNotFoundError(f"Khong tim thay {cpp_path}")
    subprocess.run(
        ["g++", "-O3", "-std=c++17", "-pthread", str(cpp_path), "-o", str(bin_path)],
        check=True,
    )
    return bin_path


def pack_npy_dir_to_npz(npy_dir: Path, out_npz_path: Path, compresslevel: int = 3) -> None:
    out_npz_path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(str(out_npz_path), "w", compression=zipfile.ZIP_DEFLATED, compresslevel=compresslevel) as zf:
        for p in sorted(npy_dir.glob("*.npy")):
            zf.write(str(p), arcname=p.name)


def hf_commit_with_retry(api, **kwargs):
    last_err = None
    for attempt in range(1, 8):
        try:
            return api.create_commit(**kwargs)
        except Exception as e:
            last_err = e
            wait_s = min(30, 3 * attempt)
            print(f"[HF Retry {attempt}/7] create_commit gap loi: {e} -> thu lai sau {wait_s}s", flush=True)
            time.sleep(wait_s)
    raise last_err


def main():
    parser = argparse.ArgumentParser(description="Merge worker JSONL, upload to HF Bucket, pack NPZ, upload to HF Dataset")
    parser.add_argument("--worker-id", required=True, type=str)
    parser.add_argument("--run-id", required=True, type=str)
    parser.add_argument("--data-dir", default="data", type=str)
    parser.add_argument("--hf-bucket", default="australia1/myrandombucket", type=str)
    parser.add_argument("--hf-dataset", default="australia1/harenn-hkv3-npz", type=str)
    parser.add_argument("--compresslevel", default=3, type=int)
    args = parser.parse_args()

    token = os.environ.get("HF_TOKEN", "").strip()
    if not token:
        print("::error::HF_TOKEN secret is not set in Repository Secrets!")
        sys.exit(1)

    data_dir = Path(args.data_dir)
    raw_files = sorted(glob.glob(str(data_dir / "*.json")) + glob.glob(str(data_dir / "*.jsonl")))
    print(f"Total raw files generated by Worker {args.worker_id}: {len(raw_files)}", flush=True)
    if not raw_files:
        print("No new data files generated to upload.")
        return

    ts = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
    wid_str = args.worker_id
    try:
        wid_pad = f"{int(wid_str):02d}"
    except ValueError:
        wid_pad = wid_str

    packed_filename = f"hnn_w{wid_str}_{args.run_id}_{ts}.jsonl"
    packed_path = data_dir / packed_filename

    total_positions = 0
    print(f"Merging {len(raw_files)} files into {packed_filename}...", flush=True)
    with open(packed_path, "w", encoding="utf-8") as out_f:
        for f in raw_files:
            if Path(f) == packed_path:
                continue
            if f.endswith(".json"):
                try:
                    with open(f, "r", encoding="utf-8") as in_f:
                        data = json.load(in_f)
                    for p in data.get("positions", []):
                        out_f.write(json.dumps(p) + "\n")
                        total_positions += 1
                except Exception as e:
                    print(f"Warning: skipped corrupted file {f}: {e}", flush=True)
            else:
                try:
                    with open(f, "r", encoding="utf-8") as in_f:
                        for line in in_f:
                            line = line.strip()
                            if line:
                                out_f.write(line + "\n")
                                total_positions += 1
                except Exception as e:
                    print(f"Warning: skipped corrupted file {f}: {e}", flush=True)
            try:
                Path(f).unlink(missing_ok=True)
            except Exception:
                pass

    if total_positions == 0:
        print("No valid positions extracted.")
        return

    size_mb = packed_path.stat().st_size / (1024 * 1024)
    print(f"Successfully merged {total_positions:,} positions into {packed_filename} ({size_mb:.2f} MB)", flush=True)

    from huggingface_hub import CommitOperationAdd, HfApi
    api = HfApi(token=token)

    print(f"Uploading {packed_filename} to HF bucket '{args.hf_bucket}'...", flush=True)
    t0 = time.time()
    api.batch_bucket_files(args.hf_bucket, add=[(str(packed_path), packed_filename)])
    print(f"Bucket JSONL upload completed in {time.time() - t0:.2f}s!", flush=True)

    # Nén sang NPZ bằng C++ fast_pack
    repo_dir = Path(__file__).resolve().parent
    fast_pack_bin = compile_fast_pack(repo_dir, Path("/tmp/fast_pack"))
    npy_dir = Path(f"/tmp/npy_w{wid_str}_{args.run_id}")
    shutil.rmtree(npy_dir, ignore_errors=True)
    npy_dir.mkdir(parents=True, exist_ok=True)

    t1 = time.time()
    res = subprocess.run(
        [str(fast_pack_bin), str(npy_dir), "1", str(packed_path)],
        capture_output=True, text=True, check=True,
    )
    raw_n, uniq_n = [int(x) for x in res.stdout.strip().split()[:2]]
    packed_path.unlink(missing_ok=True)

    npz_filename = f"hkv3_r{args.run_id}_w{wid_pad}_{ts}.npz"
    npz_path = Path("/tmp") / npz_filename
    pack_npy_dir_to_npz(npy_dir, npz_path, compresslevel=args.compresslevel)
    shutil.rmtree(npy_dir, ignore_errors=True)

    npz_mb = npz_path.stat().st_size / (1024 * 1024)
    print(
        f"[FastPack] {npz_filename}: {raw_n:,} raw -> {uniq_n:,} unique | "
        f"{npz_mb:.2f} MB (compress={args.compresslevel}) in {time.time() - t1:.2f}s",
        flush=True,
    )

    meta_filename = f"w{wid_pad}_{ts}.meta.json"
    meta_path = Path("/tmp") / meta_filename
    meta_path.write_text(
        json.dumps(
            {
                "jsonl": packed_filename,
                "shard": npz_filename,
                "shard_repo_path": f"shards/r{args.run_id}/{npz_filename}",
                "worker_id": wid_str,
                "run_id": args.run_id,
                "raw_positions": raw_n,
                "unique_positions": uniq_n,
                "npz_bytes": npz_path.stat().st_size,
            },
            indent=2,
        ),
        encoding="utf-8",
    )

    api.create_repo(repo_id=args.hf_dataset, repo_type="dataset", exist_ok=True)
    t2 = time.time()
    hf_commit_with_retry(
        api,
        repo_id=args.hf_dataset,
        repo_type="dataset",
        operations=[
            CommitOperationAdd(
                path_in_repo=f"shards/r{args.run_id}/{npz_filename}",
                path_or_fileobj=str(npz_path),
            ),
            CommitOperationAdd(
                path_in_repo=f"staging/r{args.run_id}/{meta_filename}",
                path_or_fileobj=str(meta_path),
            ),
        ],
        commit_message=f"Add NPZ shard + metadata w{wid_pad} for run {args.run_id}",
    )
    print(f"Uploaded NPZ + metadata to HF dataset '{args.hf_dataset}' in {time.time() - t2:.2f}s!", flush=True)


if __name__ == "__main__":
    main()
